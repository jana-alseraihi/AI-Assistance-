#!/usr/bin/env python3
"""Build sharepoint/pelli-sharepoint.txt: Pelli's code, style and pictures in ONE text file.

Classic SharePoint's Content Editor web part can point its "Content Link" to a .txt file and runs
what is inside. One .txt file avoids companies' blocks on .js/.css uploads or attachments.
Run after any change in pelli/:   python3 sharepoint/build.py
"""
import base64, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
pelli = root / "pelli"

def data_uri(name):
    return "data:image/svg+xml;base64," + base64.b64encode((pelli / name).read_bytes()).decode()

js = (pelli / "pelli.js").read_text(encoding="utf-8").replace("</script", "<\\/script")
css = (pelli / "pelli.css").read_text(encoding="utf-8").replace("</style", "<\\/style")
version = re.search(r'version: "([^"]+)"', js).group(1)

out = f"""<!--
  Pelli v{version} for classic SharePoint: ONE file with Pelli's code, look and pictures.
  1. Upload this file to your site's "Site Assets" library.
  2. On the page: Edit Page > Add a Web Part > Media and Content > Content Editor.
  3. Edit Web Part > Content Link: the address of this file, e.g. /sites/YourSite/SiteAssets/pelli-sharepoint.txt
  Nothing here connects to GitHub or any outside site. Generated by sharepoint/build.py: do not edit by hand.
-->
<div data-pelli-ignore style="display:none"></div>
<style>
{css}
</style>
<script>
window.PELLI_IMAGES = {{ mascot: "{data_uri('pelli.svg')}", avatar: "{data_uri('pelli-avatar.svg')}" }};
</script>
<script>
if (!window.Pelli) {{
{js}
}}
</script>
<script>
(function () {{
  // ---- Settings you can change: subtitle and suggested questions -----------------------
  var settings = {{
    scope: "#DeltaPlaceHolderMain",   // search the page content, not the SharePoint ribbon and menus
    subtitle: {{ en: "Your SharePoint buddy", ar: "رفيقك في شيربوينت" }},
    suggestions: {{
      en: ["What can you do?", "Summarize this page", "What time is it?", "Give me a tip"],
      ar: ["وش تقدر تسوي؟", "لخص الصفحة", "كم الساعة؟", "عطني نصيحة"]
    }}
  }};
  // ---------------------------------------------------------------------------------------
  if (window.__pelliStarted) return;  // only once, even if the web part is added twice
  window.__pelliStarted = true;
  function start() {{
    if (!document.querySelector(settings.scope)) settings.scope = null; // older SharePoint: whole page
    settings.lang = (document.documentElement.lang || "").toLowerCase().indexOf("ar") === 0 ? "ar" : "en";
    window.Pelli.init(settings);
  }}
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start); else start();
}})();
</script>
"""
target = root / "sharepoint" / "pelli-sharepoint.txt"
target.write_text(out, encoding="utf-8")
print(f"Wrote {target.relative_to(root)} (Pelli v{version}, {len(out.encode()) // 1024} KB)")
